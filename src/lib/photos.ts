import { getCollection, type CollectionEntry } from 'astro:content';

export type PhotoCollection = CollectionEntry<'photoCollections'>;

export interface Photo {
  id: string; // `${collectionId}/${imageId}`
  collectionId: string;
  imageId: string;
  href: string; // `/foto/${collectionId}/${imageId}`
  src: string;
  thumb: string;
  width: number;
  height: number;
  credit: string | null;
  caption: string | null;
  sortOrder: number;
  imageCount: number;
  // Inherited from parent collection:
  collectionTitle: string;
  publishedAt: string;
  authors: string[];
  photographers: string[];
  prefix: string | null;
  series: string | null;
  manchet: string | null;
  introMarkdown: string | null;
  tags: string[];
  genre: string | null;
}

export function imageUrl(collectionId: string, filename: string): string {
  return `/media/photo-collections/${collectionId}/images/${filename}`;
}

/** Generated by scripts/make-thumbs.mjs (640px WebP). */
export function thumbUrl(collectionId: string, filename: string): string {
  return `/media/thumbs/${collectionId}/${filename.replace(/\.[^.]+$/, '')}.webp`;
}

export function photoHref(collectionId: string, imageId: string): string {
  return `/foto/${collectionId}/${imageId}`;
}

/** Stable URL slug for tag display names (æ→ae, ø→oe, å→aa). */
export function slugifyTag(tag: string): string {
  return tag
    .trim()
    .replace(/æ/gi, 'ae')
    .replace(/ø/gi, 'oe')
    .replace(/å/gi, 'aa')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/-+/g, '-');
}

export function tagHref(tag: string): string {
  return `/t/${slugifyTag(tag)}`;
}

export function collectionCoverUrl(collection: PhotoCollection): string | null {
  const coverId = collection.data.coverImage;
  const cover =
    collection.data.images.find((img) => img.id === coverId) ?? collection.data.images[0];
  if (!cover) return null;
  return imageUrl(collection.data.id, cover.filename);
}

export function flattenCollectionPhotos(collection: PhotoCollection): Photo[] {
  const d = collection.data;
  const sortedImages = [...d.images].sort((a, b) => a.sortOrder - b.sortOrder);
  const fallbackCredit = d.photographers.length > 0 ? d.photographers.join(', ') : null;

  return sortedImages.map((img) => ({
    id: `${d.id}/${img.id}`,
    collectionId: d.id,
    imageId: img.id,
    href: photoHref(d.id, img.id),
    src: imageUrl(d.id, img.filename),
    thumb: thumbUrl(d.id, img.filename),
    width: img.width ?? 940,
    height: img.height ?? 627,
    credit: img.credit || fallbackCredit,
    caption: img.caption ?? null,
    sortOrder: img.sortOrder,
    imageCount: sortedImages.length,
    collectionTitle: d.title,
    publishedAt: d.publishedAt,
    authors: d.authors,
    photographers: d.photographers,
    prefix: d.prefix ?? null,
    series: d.series ?? null,
    manchet: d.manchet ?? null,
    introMarkdown: d.introMarkdown ?? null,
    tags: img.tags?.length ? [...new Set([...d.tags, ...img.tags])] : d.tags,
    genre: d.genre ?? null,
  }));
}

/** Prod-only caches so ~2k prerendered pages share one scan; dev stays fresh. */
let photosCache: Promise<Photo[]> | null = null;
let navTagsCache = new Map<number, Promise<string[]>>();
let archiveStatsCache: Promise<ArchiveStats> | null = null;

export interface ArchiveStats {
  photoCount: number;
  collectionCount: number;
  tagCount: number;
}

export async function getAllPhotos(): Promise<Photo[]> {
  const load = async () => {
    const collections = (await getCollection('photoCollections')).sort(sortCollectionsNewest);
    return collections.flatMap(flattenCollectionPhotos);
  };

  if (!import.meta.env.PROD) return load();
  photosCache ??= load();
  return photosCache;
}

/** Top tags for the Unsplash-style header filter row (by photo count). */
export async function getNavTags(limit = 10): Promise<string[]> {
  const load = async () => {
    const photos = await getAllPhotos();
    const counts = new Map<string, number>();
    for (const photo of photos) {
      for (const tag of photo.tags) {
        counts.set(tag, (counts.get(tag) ?? 0) + 1);
      }
    }
    return [...counts.entries()]
      .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0], 'da'))
      .slice(0, limit)
      .map(([tag]) => tag);
  };

  if (!import.meta.env.PROD) return load();
  let cached = navTagsCache.get(limit);
  if (!cached) {
    cached = load();
    navTagsCache.set(limit, cached);
  }
  return cached;
}

export async function getArchiveStats(): Promise<ArchiveStats> {
  const load = async (): Promise<ArchiveStats> => {
    const collections = await getCollection('photoCollections');
    const photos = await getAllPhotos();
    const tags = new Set<string>();
    for (const photo of photos) {
      for (const tag of photo.tags) tags.add(tag);
    }
    return {
      photoCount: photos.length,
      collectionCount: collections.length,
      tagCount: tags.size,
    };
  };

  if (!import.meta.env.PROD) return load();
  archiveStatsCache ??= load();
  return archiveStatsCache;
}

export function photoMatchesQuery(photo: Photo, query: string): boolean {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  const haystack = [
    photo.collectionTitle,
    photo.caption ?? '',
    photo.credit ?? '',
    photo.prefix ?? '',
    photo.genre ?? '',
    ...photo.tags,
    ...photo.authors,
    ...photo.photographers,
  ]
    .join(' ')
    .toLowerCase();
  return haystack.includes(q);
}

export function formatDate(iso: string): string {
  return new Intl.DateTimeFormat('da-DK', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  }).format(new Date(iso));
}

export function byline(authors: string[]): string {
  if (authors.length === 0) return '';
  if (authors.length === 1) return `Af ${authors[0]}`;
  if (authors.length === 2) return `Af ${authors[0]} og ${authors[1]}`;
  const head = authors.slice(0, -1).join(', ');
  return `Af ${head} og ${authors[authors.length - 1]}`;
}

export function sortCollectionsNewest(a: PhotoCollection, b: PhotoCollection) {
  return +new Date(b.data.publishedAt) - +new Date(a.data.publishedAt);
}

export function sortCollectionsOldest(a: PhotoCollection, b: PhotoCollection) {
  return +new Date(a.data.publishedAt) - +new Date(b.data.publishedAt);
}

/** Pack photos into N columns (shortest-column-first) for masonry layout. */
export function packIntoColumns(photos: Photo[], columnCount: number): Photo[][] {
  const n = Math.max(1, columnCount);
  const columns: Photo[][] = Array.from({ length: n }, () => []);
  const heights = Array.from({ length: n }, () => 0);

  for (const photo of photos) {
    let shortest = 0;
    for (let k = 1; k < n; k++) {
      if (heights[k] < heights[shortest]) shortest = k;
    }
    columns[shortest].push(photo);
    heights[shortest] += photo.height / photo.width;
  }

  return columns;
}
