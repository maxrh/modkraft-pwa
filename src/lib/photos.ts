import { getCollection, type CollectionEntry } from 'astro:content';

export type PhotoCollection = CollectionEntry<'photoCollections'>;

export interface Photo {
  id: string; // `${collectionId}/${imageId}`
  collectionId: string;
  imageId: string;
  href: string; // `/foto/${collectionId}/${imageId}`
  src: string;
  thumb: string;
  display: string;
  filename: string;
  width: number;
  height: number;
  credit: string | null;
  caption: string | null;
  sortOrder: number;
  imageCount: number;
  // Inherited from parent collection:
  collectionTitle: string;
  publishedAt: string;
  authors: string[];
  photographers: string[];
  prefix: string | null;
  series: string | null;
  manchet: string | null;
  introMarkdown: string | null;
  tags: string[];
  genre: string | null;
  sourceType: string | null;
}

/** Modkraft source kinds shown in the UI (artikel-foto maps to fotoserie). */
export type CollectionKind = 'fotoserie' | 'fotoblog';

export function collectionKind(sourceType: string | null | undefined): CollectionKind {
  return sourceType === 'fotoblog' ? 'fotoblog' : 'fotoserie';
}

export function collectionKindLabel(
  sourceType: string | null | undefined,
  form: 'singular' | 'plural' = 'singular',
): string {
  const kind = collectionKind(sourceType);
  if (form === 'plural') return kind === 'fotoblog' ? 'Fotoblogs' : 'Fotoserier';
  return kind === 'fotoblog' ? 'Fotoblog' : 'Fotoserie';
}

export function imageUrl(collectionId: string, filename: string): string {
  return `/media/photo-collections/${collectionId}/images/${filename}`;
}

/** Generated by scripts/make-thumbs.mjs (640px WebP). */
export function thumbUrl(collectionId: string, filename: string): string {
  return `/media/thumbs/${collectionId}/${filename.replace(/\.[^.]+$/, '')}.webp`;
}

/** Generated by scripts/make-thumbs.mjs (1400px WebP). */
export function displayUrl(collectionId: string, filename: string): string {
  return `/media/display/${collectionId}/${filename.replace(/\.[^.]+$/, '')}.webp`;
}

export function photoHref(collectionId: string, imageId: string): string {
  return `/foto/${collectionId}/${imageId}`;
}

/** Stable URL slug for tag display names (æ→ae, ø→oe, å→aa). */
export function slugifyTag(tag: string): string {
  return tag
    .trim()
    .replace(/æ/gi, 'ae')
    .replace(/ø/gi, 'oe')
    .replace(/å/gi, 'aa')
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .replace(/-+/g, '-');
}

export function tagHref(tag: string): string {
  return `/t/${slugifyTag(tag)}`;
}

/**
 * Prefer a stable display label when several tags share a slug
 * (e.g. "Koncert" vs "koncert"). More photos wins; then da locale.
 */
export function preferTagLabel(a: string, b: string, countA = 0, countB = 0): string {
  if (countA !== countB) return countA > countB ? a : b;
  // Prefer any capital letter (Title/proper case) over all-lowercase
  const aCap = /[A-ZÆØÅ]/.test(a);
  const bCap = /[A-ZÆØÅ]/.test(b);
  if (aCap !== bCap) return aCap ? a : b;
  return a.localeCompare(b, 'da') <= 0 ? a : b;
}

export function collectionCoverUrl(collection: PhotoCollection): string | null {
  const coverId = collection.data.coverImage;
  const cover =
    collection.data.images.find((img) => img.id === coverId) ?? collection.data.images[0];
  if (!cover) return null;
  return imageUrl(collection.data.id, cover.filename);
}

/** Compact card payload for mosaic tiles linking to a fotoserie. */
export interface CollectionCardData {
  id: string;
  href: string;
  thumb: string;
  width: number;
  height: number;
  title: string;
  badge: string;
  meta: string;
  publishedAt: string;
  alt: string;
}

export function collectionCardData(collection: PhotoCollection): CollectionCardData | null {
  const d = collection.data;
  const coverId = d.coverImage;
  const cover = d.images.find((img) => img.id === coverId) ?? d.images[0];
  if (!cover) return null;

  const imageCount = d.images.length;
  const fotoWord = imageCount === 1 ? 'foto' : 'fotos';
  const credit =
    d.photographers.length > 0
      ? d.photographers.join(', ')
      : d.authors.length > 0
        ? byline(d.authors)
        : '';
  const date = formatDate(d.publishedAt);
  const meta = [date, credit].filter(Boolean).join(' · ');

  return {
    id: d.id,
    href: `/fotoserie/${d.id}`,
    thumb: thumbUrl(d.id, cover.filename),
    width: cover.width ?? 940,
    height: cover.height ?? 627,
    title: d.title,
    badge: `${imageCount} ${fotoWord}`,
    meta,
    publishedAt: d.publishedAt,
    alt: d.title,
  };
}

/** Unique series from a photo set, preserving first-seen order. */
export function collectionCardsFromPhotos(
  photos: Photo[],
  collections: PhotoCollection[],
): CollectionCardData[] {
  const byId = new Map(collections.map((c) => [c.data.id, c]));
  const seen = new Set<string>();
  const out: CollectionCardData[] = [];
  for (const photo of photos) {
    if (seen.has(photo.collectionId)) continue;
    seen.add(photo.collectionId);
    const collection = byId.get(photo.collectionId);
    if (!collection) continue;
    const card = collectionCardData(collection);
    if (card) out.push(card);
  }
  return out;
}

export function flattenCollectionPhotos(collection: PhotoCollection): Photo[] {
  const d = collection.data;
  const sortedImages = [...d.images].sort((a, b) => a.sortOrder - b.sortOrder);
  const fallbackCredit = d.photographers.length > 0 ? d.photographers.join(', ') : null;

  return sortedImages.map((img) => ({
    id: `${d.id}/${img.id}`,
    collectionId: d.id,
    imageId: img.id,
    href: photoHref(d.id, img.id),
    src: imageUrl(d.id, img.filename),
    thumb: thumbUrl(d.id, img.filename),
    display: displayUrl(d.id, img.filename),
    filename: img.filename,
    width: img.width ?? 940,
    height: img.height ?? 627,
    credit: img.credit || fallbackCredit,
    caption: img.caption ?? null,
    sortOrder: img.sortOrder,
    imageCount: sortedImages.length,
    collectionTitle: d.title,
    publishedAt: d.publishedAt,
    authors: d.authors,
    photographers: d.photographers,
    prefix: d.prefix ?? null,
    series: d.series ?? null,
    manchet: d.manchet ?? null,
    introMarkdown: d.introMarkdown ?? null,
    tags: img.tags?.length ? [...new Set([...d.tags, ...img.tags])] : d.tags,
    genre: d.genre ?? null,
    sourceType: d.sourceType ?? null,
  }));
}

/** Prod-only caches so ~2k prerendered pages share one scan; dev stays fresh. */
let photosCache: Promise<Photo[]> | null = null;
let tagBucketsCache: Promise<TagBucket[]> | null = null;
let photographersCache: Promise<PhotographerInfo[]> | null = null;
let searchCollectionsCache: Promise<SearchCollection[]> | null = null;
const navTagsCache = new Map<number, Promise<string[]>>();
let archiveStatsCache: Promise<ArchiveStats> | null = null;

/** Skip a nav candidate when it nearly duplicates an already chosen tag. */
const NAV_JACCARD_MAX = 0.6;

export interface TagInfo {
  label: string;
  slug: string;
  count: number;
}

interface TagBucket extends TagInfo {
  photoIds: Set<string>;
}

export interface PhotographerInfo {
  label: string;
  count: number;
}

export interface SearchCollection {
  title: string;
  href: string;
  kind: 'Fotoserie' | 'Fotoblog';
  count: number;
}

export interface ArchiveStats {
  photoCount: number;
  collectionCount: number;
  tagCount: number;
}

export async function getAllPhotos(): Promise<Photo[]> {
  const load = async () => {
    const collections = (await getCollection('photoCollections')).sort(sortCollectionsNewest);
    return collections.flatMap(flattenCollectionPhotos);
  };

  if (!import.meta.env.PROD) return load();
  photosCache ??= load();
  return photosCache;
}

function jaccard(a: Set<string>, b: Set<string>): number {
  const [small, large] = a.size <= b.size ? [a, b] : [b, a];
  let intersection = 0;
  for (const id of small) if (large.has(id)) intersection++;
  const union = a.size + b.size - intersection;
  return union === 0 ? 0 : intersection / union;
}

let loggedNavSkips = false;

/** Tags by photo count, each with the photo ids it covers. */
async function getTagBuckets(): Promise<TagBucket[]> {
  const load = async (): Promise<TagBucket[]> => {
    const photos = await getAllPhotos();
    const bySlug = new Map<string, TagBucket & { labelCounts: Map<string, number> }>();
    for (const photo of photos) {
      const seen = new Set<string>();
      for (const tag of photo.tags) {
        const slug = slugifyTag(tag);
        if (!slug || seen.has(slug)) continue;
        seen.add(slug);
        let bucket = bySlug.get(slug);
        if (!bucket) {
          bucket = { label: tag, slug, count: 0, photoIds: new Set(), labelCounts: new Map() };
          bySlug.set(slug, bucket);
        }
        bucket.labelCounts.set(tag, (bucket.labelCounts.get(tag) ?? 0) + 1);
        bucket.label = preferTagLabel(
          bucket.label,
          tag,
          bucket.labelCounts.get(bucket.label) ?? 0,
          bucket.labelCounts.get(tag) ?? 0,
        );
        bucket.photoIds.add(photo.id);
        bucket.count++;
      }
    }
    return [...bySlug.values()]
      .map(({ label, slug, count, photoIds }) => ({ label, slug, count, photoIds }))
      .sort((a, b) => b.count - a.count || a.label.localeCompare(b.label, 'da'));
  };

  if (!import.meta.env.PROD) return load();
  tagBucketsCache ??= load();
  return tagBucketsCache;
}

/** All unique tags sorted by photo count (for search autocomplete). */
export async function getAllTags(): Promise<TagInfo[]> {
  const buckets = await getTagBuckets();
  return buckets.map(({ label, slug, count }) => ({ label, slug, count }));
}

/**
 * Header filter row: top tags by photo count, skipping near-duplicates
 * (Jaccard >= 0.6 against an already chosen tag). Larger tag wins.
 */
export async function getNavTags(limit = 10): Promise<string[]> {
  const load = async () => {
    const buckets = await getTagBuckets();
    const selected: TagBucket[] = [];
    const skips: string[] = [];
    for (const candidate of buckets) {
      let clash: { label: string; score: number } | null = null;
      for (const chosen of selected) {
        const score = jaccard(candidate.photoIds, chosen.photoIds);
        if (score >= NAV_JACCARD_MAX) {
          clash = { label: chosen.label, score };
          break;
        }
      }
      if (clash) {
        skips.push(
          `[nav] skip ${candidate.label} (${candidate.count}) ~ ${clash.label} jaccard=${clash.score.toFixed(2)}`,
        );
        continue;
      }
      selected.push(candidate);
      if (selected.length >= limit) break;
    }
    if (import.meta.env.DEV && !loggedNavSkips) {
      loggedNavSkips = true;
      for (const line of skips) console.info(line);
    }
    return selected.map((tag) => tag.label);
  };

  if (!import.meta.env.PROD) return load();
  let cached = navTagsCache.get(limit);
  if (!cached) {
    cached = load();
    navTagsCache.set(limit, cached);
  }
  return cached;
}

const PHOTOGRAPHER_JUNK = new Set(['privat']);

/** Split a credit into person names. Drops empty, "Privat", and domain fragments. */
function splitCreditNames(raw: string): string[] {
  return raw
    .split(/\s*(?:,|\/| og )\s*/i)
    .map((part) => part.trim())
    .filter((part) => part.length > 0 && !part.includes('.') && !PHOTOGRAPHER_JUNK.has(part.toLowerCase()));
}

/** Photographers by photo count. Case variants share one label (most common casing). */
export async function getPhotographers(): Promise<PhotographerInfo[]> {
  const load = async (): Promise<PhotographerInfo[]> => {
    const photos = await getAllPhotos();
    const byKey = new Map<string, { label: string; labelCounts: Map<string, number>; photoIds: Set<string> }>();
    for (const photo of photos) {
      const raw = photo.credit ? [...photo.photographers, photo.credit] : [...photo.photographers];
      const seen = new Map<string, string>();
      for (const piece of raw) {
        for (const name of splitCreditNames(piece)) {
          const key = name.toLocaleLowerCase('da');
          if (!seen.has(key)) seen.set(key, name);
        }
      }
      for (const [key, name] of seen) {
        let bucket = byKey.get(key);
        if (!bucket) {
          bucket = { label: name, labelCounts: new Map(), photoIds: new Set() };
          byKey.set(key, bucket);
        }
        bucket.labelCounts.set(name, (bucket.labelCounts.get(name) ?? 0) + 1);
        bucket.label = preferTagLabel(
          bucket.label,
          name,
          bucket.labelCounts.get(bucket.label) ?? 0,
          bucket.labelCounts.get(name) ?? 0,
        );
        bucket.photoIds.add(photo.id);
      }
    }
    return [...byKey.values()]
      .map(({ label, photoIds }) => ({ label, count: photoIds.size }))
      .sort((a, b) => b.count - a.count || a.label.localeCompare(b.label, 'da'));
  };

  if (!import.meta.env.PROD) return load();
  photographersCache ??= load();
  return photographersCache;
}

/** Collection and parent-fotoblog titles for search suggestions. */
export async function getSearchCollections(): Promise<SearchCollection[]> {
  const load = async (): Promise<SearchCollection[]> => {
    const collections = await getCollection('photoCollections');
    const seriesList = await getCollection('photoSeries');
    const rows: SearchCollection[] = collections.map((collection) => ({
      title: collection.data.title,
      href: `/fotoserie/${collection.id}`,
      kind: 'Fotoserie',
      count: collection.data.images.length,
    }));
    for (const series of seriesList) {
      const chapters = collections.filter((collection) => collection.data.series === series.data.id);
      const count = chapters.reduce((sum, collection) => sum + collection.data.images.length, 0);
      rows.push({
        title: series.data.title,
        href: `/fotoblog/${series.data.id}`,
        kind: 'Fotoblog',
        count,
      });
    }
    return rows.sort((a, b) => b.count - a.count || a.title.localeCompare(b.title, 'da'));
  };

  if (!import.meta.env.PROD) return load();
  searchCollectionsCache ??= load();
  return searchCollectionsCache;
}

export async function getArchiveStats(): Promise<ArchiveStats> {
  const load = async (): Promise<ArchiveStats> => {
    const collections = await getCollection('photoCollections');
    const photos = await getAllPhotos();
    const tagSlugs = new Set<string>();
    for (const photo of photos) {
      for (const tag of photo.tags) {
        const slug = slugifyTag(tag);
        if (slug) tagSlugs.add(slug);
      }
    }
    return {
      photoCount: photos.length,
      collectionCount: collections.length,
      tagCount: tagSlugs.size,
    };
  };

  if (!import.meta.env.PROD) return load();
  archiveStatsCache ??= load();
  return archiveStatsCache;
}

export function photoMatchesQuery(photo: Photo, query: string): boolean {
  const q = query.trim().toLowerCase();
  if (!q) return true;
  const haystack = [
    photo.collectionTitle,
    photo.caption ?? '',
    photo.credit ?? '',
    photo.prefix ?? '',
    ...photo.tags,
    ...photo.authors,
    ...photo.photographers,
  ]
    .join(' ')
    .toLowerCase();
  return haystack.includes(q);
}

export function formatDate(iso: string): string {
  return new Intl.DateTimeFormat('da-DK', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  }).format(new Date(iso));
}

/** Title, description, and alt for a foto page. Unique even when the photo has no caption. */
export function photoPageSeo(photo: Photo): { title: string; description: string; alt: string } {
  const credit = photo.credit?.trim() || null;
  const kind = collectionKindLabel(photo.sourceType).toLowerCase();
  const alt = photo.caption
    ? photo.caption
    : credit
      ? `${photo.collectionTitle}, foto ${photo.sortOrder}, ${credit}`
      : `${photo.collectionTitle}, foto ${photo.sortOrder}`;
  const title = photo.caption
    ? `${photo.caption} — ${photo.collectionTitle}`
    : credit
      ? `${photo.collectionTitle}, foto ${photo.sortOrder} — ${credit}`
      : `${photo.collectionTitle}, foto ${photo.sortOrder} af ${photo.imageCount}`;

  let summary = `Foto ${photo.sortOrder} af ${photo.imageCount} fra ${kind} "${photo.collectionTitle}"`;
  if (credit) summary += `, ${credit}`;
  if (photo.publishedAt) summary += `, ${formatDate(photo.publishedAt)}`;
  summary += '.';
  const tags = photo.tags.filter(Boolean).slice(0, 5);
  const parts = [photo.caption?.trim(), summary, tags.length ? `${tags.join(', ')}.` : ''].filter(
    (part): part is string => Boolean(part),
  );
  let description = parts.join(' ');
  if (description.length > 180) {
    description = `${description.slice(0, 177).replace(/\s+\S*$/, '')}…`;
  }
  return { title, description, alt };
}

export function byline(authors: string[]): string {
  if (authors.length === 0) return '';
  if (authors.length === 1) return `Af ${authors[0]}`;
  if (authors.length === 2) return `Af ${authors[0]} og ${authors[1]}`;
  const head = authors.slice(0, -1).join(', ');
  return `Af ${head} og ${authors[authors.length - 1]}`;
}

export function sortCollectionsNewest(a: PhotoCollection, b: PhotoCollection) {
  return +new Date(b.data.publishedAt) - +new Date(a.data.publishedAt);
}

export function sortCollectionsOldest(a: PhotoCollection, b: PhotoCollection) {
  return +new Date(a.data.publishedAt) - +new Date(b.data.publishedAt);
}

/** Pack items into N columns (shortest-column-first) for masonry layout. */
export function packIntoColumns<T extends { width: number; height: number }>(
  items: T[],
  columnCount: number,
): T[][] {
  const n = Math.max(1, columnCount);
  const columns: T[][] = Array.from({ length: n }, () => []);
  const heights = Array.from({ length: n }, () => 0);

  for (const item of items) {
    let shortest = 0;
    for (let k = 1; k < n; k++) {
      if (heights[k] < heights[shortest]) shortest = k;
    }
    columns[shortest].push(item);
    heights[shortest] += item.height / item.width;
  }

  return columns;
}
